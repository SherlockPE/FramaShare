ALTER TABLE "User" ADD COLUMN "name" TEXT NOT NULL DEFAULT '',
ADD COLUMN "role" TEXT NOT NULL DEFAULT 'author',
ADD COLUMN "quota" INTEGER NOT NULL DEFAULT 1000000000;
